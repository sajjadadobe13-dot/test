// Proves the mobile crypto is byte-compatible with the Python PC host.
//
// The vectors below were produced by the REAL host crypto
// (peerdesk/crypto.py + the `cryptography` package). If these pass, the mobile
// app can complete the encrypted handshake and read/write session records that
// the PC host accepts.
import 'dart:convert';
import 'dart:typed_data';

import 'package:cryptography/cryptography.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:peerdesk_mobile/core/crypto.dart' as pd;

Uint8List hx(String s) {
  final out = Uint8List(s.length ~/ 2);
  for (var i = 0; i < out.length; i++) {
    out[i] = int.parse(s.substring(i * 2, i * 2 + 2), radix: 16);
  }
  return out;
}

String toHex(List<int> b) =>
    b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

// --- vectors generated by the Python host (see scratchpad/vectors.json) ---
const fernetKeyHex =
    '000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f';
const fernetPlaintextHex =
    '506565724465736b20696e7465726f702000010220e29c93206672616d65';
const fernetTokenB64 =
    'gAAAAABq1Ruxs8tDYclJvhnr4jm7SnppZ1gq08GTOPgZTYEgWy8v4MJOmKZOJKkVdYfj5_ezJl04jjcaFle3gpIxVx_syyRkagElYB-rBXAnWLGBtcUCMO4=';
const xPrivAHex =
    '0858f358a62714cde48dc5a1abb7d14610db57068f9b21387acb96dfcdb99841';
const xPubAHex =
    'ce258b3a58eef161f67afceedf1898b21444d7431a8aaa975d3e0d8bb53d1509';
const xPubBHex =
    'e4941f20fc2544a81220b8fe0cffd23f3f59f3d2cb05ea262cee53be478b2e03';
const xHkdfKeyHex =
    '4feca172f9f16641f8f92fcf9803c69185e60b11ec4d8f37d9e4fa0eaaecfc0c';
const pbSaltHex = '7369787465656e2d627974652d73616c';
const pbKeyHex =
    '0517063b04419f28c05885bfdb393e5ebdd008b1802eb2173463e0c5e6055ca6';
const chalKeyHex =
    '202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f';
const chalNonceHex =
    '612d66697865642d33322d627974652d6e6f6e63652d666f722d746573747321';
const chalAnswerHex =
    '337c390f9cb280dfbb8312977067c89302cc88425979f6c9ff143206ed1422ce';

void main() {
  test('Fernet: decrypts a token produced by the Python host', () async {
    final chan = pd.SecureChannel(hx(fernetKeyHex));
    final plain = await chan.decrypt(utf8.encode(fernetTokenB64));
    expect(toHex(plain), fernetPlaintextHex);
  });

  test('Fernet: Dart round-trip (encrypt then decrypt)', () async {
    final chan = pd.SecureChannel(hx(fernetKeyHex));
    final msg = utf8.encode('round trip ✓ 123');
    final token = await chan.encrypt(msg);
    final back = await chan.decrypt(token);
    expect(back, msg);
  });

  test('Fernet: tampered token is rejected', () async {
    final chan = pd.SecureChannel(hx(fernetKeyHex));
    final token = Uint8List.fromList(await chan.encrypt(utf8.encode('hi')));
    token[token.length - 2] ^= 0x01; // flip a bit in the (base64) mac region
    expect(() => chan.decrypt(token), throwsA(isA<Object>()));
  });

  test('X25519 + HKDF derives the same session key as the host', () async {
    final keyPair = SimpleKeyPairData(
      hx(xPrivAHex),
      publicKey: SimplePublicKey(hx(xPubAHex), type: KeyPairType.x25519),
      type: KeyPairType.x25519,
    );
    final derived = await pd.deriveSharedKey(keyPair, hx(xPubBHex));
    expect(toHex(derived), xHkdfKeyHex);
  });

  test('PBKDF2-HMAC-SHA256 matches the host', () async {
    final key = await pd.deriveKeyPbkdf2('hunter2', hx(pbSaltHex));
    expect(toHex(key), pbKeyHex);
  });

  test('challenge answer (HMAC-SHA256) matches the host', () async {
    final ans = await pd.challengeAnswer(hx(chalKeyHex), hx(chalNonceHex));
    expect(toHex(ans), chalAnswerHex);
  });
}
