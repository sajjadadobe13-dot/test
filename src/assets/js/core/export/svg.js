import { LAYERS, LAYER_ORDER, PT } from './compose.js';

const n = (v) => (Math.round(v * 1000) / 1000).toString();
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function pathData(pts, closed) {
  let d = `M${n(pts[0][0])} ${n(pts[0][1])}`;
  for (let i = 1; i < pts.length; i++) d += `L${n(pts[i][0])} ${n(pts[i][1])}`;
  return closed ? d + 'Z' : d;
}

/**
 * SVG document. Layers become Inkscape/Illustrator-compatible groups.
 * preview: screen rendering (non-scaling hairlines, CSS classes, no fixed size).
 */
export function toSVG(sheet, { preview = false, hidden = [] } = {}) {
  const { width, height, items, lineWidth } = sheet;
  const sw = preview ? 1.25 : lineWidth * PT;
  const groups = {};
  for (const it of items) (groups[it.layer] ||= []).push(it);
  const out = [];
  if (preview) {
    out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${n(width)} ${n(height)}" class="dl-svg" role="img" aria-label="${esc(sheet.meta.title || 'Dieline')} preview">`);
  } else {
    out.push('<?xml version="1.0" encoding="UTF-8" standalone="no"?>');
    out.push(`<!-- ${esc(sheet.meta.title || 'Dieline')} – generated by ${esc(sheet.meta.generator || 'DielineForge')}. Units: millimetres. -->`);
    out.push(
      `<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" width="${n(width)}mm" height="${n(height)}mm" viewBox="0 0 ${n(width)} ${n(height)}" version="1.1">`,
    );
    out.push(`<title>${esc(sheet.meta.title || 'Dieline')}</title>`);
  }
  for (const key of LAYER_ORDER) {
    const list = groups[key];
    if (!list || !list.length) continue;
    const L = LAYERS[key];
    const dash = L.dash ? ` stroke-dasharray="${L.dash.map((v) => (preview ? v * 1.6 : v)).map(n).join(' ')}"` : '';
    const ve = preview ? ' vector-effect="non-scaling-stroke"' : '';
    const vis = hidden.includes(key) ? ' style="display:none"' : '';
    const attrs = preview ? ` class="layer layer-${key}" data-layer="${key}"` : ` id="${key}" inkscape:groupmode="layer" inkscape:label="${esc(L.name)}"`;
    out.push(`<g${attrs}${vis}>`);
    const paths = list.filter((i) => i.kind === 'path');
    const texts = list.filter((i) => i.kind === 'text');
    if (paths.length) {
      const fill = L.fill ? ` fill="${L.color}" fill-opacity="${L.fill}"` : ' fill="none"';
      const width = key === 'info' ? sw * 0.6 : key === 'bleed' || key === 'safe' || key === 'guide' ? sw * 0.8 : sw;
      out.push(`<g stroke="${L.color}" stroke-width="${n(width)}"${dash}${fill} stroke-linejoin="round" stroke-linecap="round">`);
      for (const p of paths) {
        // the legend swatch of a fill layer should be a line, not a filled sliver
        const extra = L.fill && !p.closed ? ' fill="none"' : '';
        const da = p.role === 'dim' || p.role === 'block' ? ' stroke-dasharray="none"' : '';
        out.push(`<path d="${pathData(p.pts, p.closed)}"${extra}${da}${ve}/>`);
      }
      out.push('</g>');
    }
    if (texts.length) {
      out.push(`<g fill="${key === 'info' ? L.color : L.color}" font-family="Helvetica, Arial, sans-serif">`);
      for (const t of texts) {
        const rot = t.angle ? ` transform="rotate(${n(t.angle)} ${n(t.x)} ${n(t.y)})"` : '';
        const cls = preview ? ` class="t-${t.role || 'text'}"` : '';
        const fw = t.weight === 'bold' ? ' font-weight="700"' : '';
        const op = t.role === 'label' ? ' fill-opacity="0.55"' : '';
        out.push(`<text x="${n(t.x)}" y="${n(t.y)}" font-size="${n(t.size)}" text-anchor="${t.anchor || 'start'}"${fw}${op}${rot}${cls}>${esc(t.text)}</text>`);
      }
      out.push('</g>');
    }
    out.push('</g>');
  }
  out.push('</svg>');
  return out.join('\n');
}
